#!/usr/bin/env python3
"""Apply the professional navy/slate/blue palette to legacy SVG panels.

The active research chart is generated by build_research_chart.py.
"""
from pathlib import Path
import colorsys
import re
ROOT = Path(__file__).resolve().parents[1]
EXACT = {
    '#1D1714':'#0B1629', '#2B241F':'#14243C', '#F4EADB':'#F1F6FC',
    '#D8A25E':'#6EB6FF', '#C46D48':'#4DA7DB', '#596C78':'#718DB1',
    '#85966D':'#60B7D1', '#A89E8C':'#B4C6DE', '#5C5146':'#345474',
    '#7C756D':'#8099B9', '#D6C9B5':'#CBD9ED',
}

def recolor(match):
    code = match.group(0).upper()
    if code in EXACT:
        return EXACT[code]
    rgb = [int(code[i:i+2],16)/255 for i in (1,3,5)]
    h,l,s = colorsys.rgb_to_hls(*rgb)
    if s < .08 or .5 <= h <= .65:
        return code
    r,g,b = colorsys.hls_to_rgb(.595, l, min(s,.48))
    return '#'+''.join(f'{round(c*255):02X}' for c in (r,g,b))

for path in ROOT.glob('assets/**/*.svg'):
    if path.name.startswith(('jithu-', 'accuracy-')):
        continue
    text = re.sub(r'#[0-9A-Fa-f]{6}\b', recolor, path.read_text())
    text = text.replace("Georgia,'Times New Roman',serif", 'Arial,Helvetica,sans-serif')
    path.write_text(text)

# Keep scheduled refreshes consistent with the checked-in palette.
path = ROOT/'scripts/update_telemetry.py'
text = path.read_text()
for old,new in EXACT.items():
    text = text.replace(old,new)
text = text.replace("Georgia,'Times New Roman',serif", 'Arial,Helvetica,sans-serif')
path.write_text(text)
